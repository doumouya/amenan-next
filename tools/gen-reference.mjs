#!/usr/bin/env node
// gen-reference — docs/REFERENCE.md is GENERATED from the compiler's own view of the public
// surface, never written by hand. A hand-written API list is the first doc to rot: the barrel
// changes in the same commit that forgets the list. Here the list IS a query — gate 12 re-runs
// this script and diffs, so a stale REFERENCE.md is a red gate, not a hope.
//
// Two public entries, matching the package's exports map: the barrel (`amenan-next`) and the
// theme runtime (`amenan-next/theme`, its own entry so a pre-paint <head> snippet never drags
// React in). Output is DETERMINISTIC (sorted, no timestamps) — determinism is what makes
// "stale" a byte-level question.
//
// Doc: docs/DOCMAP.md routes here; the output carries its own do-not-edit banner.

import ts from "typescript";
import { writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ENTRIES = [
  { spec: "amenan-next", file: join(ROOT, "src/index.ts") },
  { spec: "amenan-next/theme", file: join(ROOT, "src/theme/theme.ts") },
];

const program = ts.createProgram(
  ENTRIES.map((e) => e.file),
  { jsx: ts.JsxEmit.ReactJSX, module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
);
const checker = program.getTypeChecker();

/** the first sentence of the declaration's leading doc comment, if any */
function docLine(sym) {
  const parts = sym.getDocumentationComment(checker);
  const text = ts.displayPartsToString(parts).trim().replace(/\s+/g, " ");
  if (!text) return "";
  const m = text.match(/^.*?[.!?](\s|$)/);
  return (m ? m[0] : text).trim();
}

function kindOf(sym) {
  const d = sym.getDeclarations()?.[0];
  if (!d) return "value";
  if (ts.isTypeAliasDeclaration(d) || ts.isInterfaceDeclaration(d)) return "type";
  if (ts.isFunctionDeclaration(d)) return /^[A-Z]/.test(sym.name) ? "component" : "function";
  if (ts.isVariableDeclaration(d)) {
    const t = checker.getTypeOfSymbolAtLocation(sym, d);
    if (t.getCallSignatures().length > 0)
      return /^[A-Z]/.test(sym.name) && sym.name !== "Symbol" ? "component" : "function";
    return "const";
  }
  if (ts.isClassDeclaration(d)) return "class";
  return "value";
}

function moduleOf(sym) {
  const d = sym.getDeclarations()?.[0];
  return d ? relative(ROOT, d.getSourceFile().fileName).replace(/\\/g, "/") : "?";
}

const sections = [];
for (const entry of ENTRIES) {
  const sf = program.getSourceFile(entry.file);
  const modSym = checker.getSymbolAtLocation(sf);
  if (!modSym) throw new Error(`no module symbol for ${entry.file}`);
  const rows = checker
    .getExportsOfModule(modSym)
    .map((s) => (s.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(s) : s))
    .map((s) => ({ name: s.name, kind: kindOf(s), module: moduleOf(s), doc: docLine(s) }))
    .sort((a, b) => a.module.localeCompare(b.module) || a.name.localeCompare(b.name));
  sections.push({ spec: entry.spec, rows });
}

let out = `# REFERENCE — the public surface, from the compiler
<!-- GENERATED by tools/gen-reference.mjs — do not edit. Gate 12 reddens a stale copy. -->

Every symbol a consumer can import, grouped by entry and source module. The one-line
descriptions are the declarations' own doc comments — fix them at the source, then
\`node tools/gen-reference.mjs\`.
`;

for (const s of sections) {
  out += `\n## \`${s.spec}\`\n\n| symbol | kind | source | what it is |\n|---|---|---|---|\n`;
  for (const r of s.rows) {
    out += `| \`${r.name}\` | ${r.kind} | \`${r.module}\` | ${r.doc.replace(/\|/g, "\\|")} |\n`;
  }
}

writeFileSync(join(ROOT, "docs/REFERENCE.md"), out);
const total = sections.reduce((n, s) => n + s.rows.length, 0);
console.log(`docs/REFERENCE.md: ${total} exported symbol(s) across ${sections.length} entr(ies)`);
